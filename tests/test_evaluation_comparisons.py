def complete_result(binding):
    ious = [.5 + .05*i for i in range(10)]
    parameters = {
        'iou_type': 'bbox', 'iou_thresholds': ious, 'recall_thresholds': [.01*i for i in range(101)],
        'area_ranges': [[0., 10000000000.]], 'area_range_labels': ['all'], 'max_detections': [1,10,100],
        'reported_max_detections': 100, 'max_detections_scope': 'per_image_per_category', 'use_categories': True,
        'box_format': 'xyxy_original_image_pixels_continuous', 'category_averaging': 'macro_over_categories_with_ground_truth',
        'no_ground_truth_ap': None, 'crowd_ignore_group_policy': 'rejected', 'score_filtering': 'none', 'nms': 'none',
        'score_tie_order': 'stable_image_input_order_then_prediction_input_order', 'ar_100_iou_thresholds': ious, 'ar_100_area': 'all'}
    rows = [{'category_id': i, 'name': name, 'ground_truth_boxes': 5 if i == 0 else 0,
             'predictions': 4 if i == 0 else 0, 'status': 'evaluated' if i == 0 else 'no_ground_truth',
             'ap_50': .4 if i == 0 else None, 'ap_50_95': .25 if i == 0 else None,
             'ar_100': .3 if i == 0 else None} for i, name in enumerate(CLASS_NAMES)]
    op_rows = [{'category_id': i, 'name': name, 'tp': 2 if i == 0 else 0,
                'fp': 2 if i == 0 else 0, 'fn': 3 if i == 0 else 0,
                'precision': .5 if i == 0 else None, 'recall': .4 if i == 0 else None}
               for i, name in enumerate(CLASS_NAMES)]
    env = binding['submission_environment']
    deps = json.loads(env['dependencies'])
    return {'metrics': {'map_50': .4, 'map_50_95': .25, 'ar_100': .3, 'status': 'evaluated',
                        'protocol': 'coco-style-bbox-subset/v1',
                        'evaluator': {'implementation': 'pycocotools.cocoeval.COCOeval', 'version': deps['pycocotools']},
                        'parameters': parameters, 'per_class': rows,
                        'counts': {'images': 1, 'images_with_ground_truth': 1, 'images_without_ground_truth': 0,
                                   'images_with_predictions': 1, 'ground_truth_boxes': 5, 'predictions': 4,
                                   'predictions_above_max_detections': 0, 'categories': 80, 'categories_with_ground_truth': 1}},
            'operating_point': {'protocol': 'class-aware-greedy-iou50/v1', 'iou_threshold': .5,
                                'score_threshold': .3, 'score_operator': '>', 'per_class': op_rows,
                                'totals': {'precision': .5, 'recall': .4, 'tp': 2, 'fp': 2, 'fn': 3}},
            'environment': {**env, 'dependencies': {k: v for k, v in deps.items() if k != 'onnx'}},
            'scope': {'images': 1, 'split': 'val', 'official_benchmark': False, 'external_audit': False,
                      'production_allowed': False, 'device_certified': False},
            'digests': dict(ModelEvaluationStore.expected_digests(binding, digest(binding)),
                            prediction_sha256=digest([]))}


class ComparisonTests(unittest.TestCase):
    def setUp(self):
        # Existing fixture creates a synthetic model/DB; no model inference.
        # Stub pagination signing material in memory: no persistent credential
        # or signing key is generated by this focused contract suite.
        key_stub = mock.patch('model_platform.store.cursor_key', return_value=b'fixed-comparison-fixture')
        key_stub.start()
        self.addCleanup(key_stub.stop)
        self.fixture = fixtures.QueueTests('test_success_keeps_model_provenance_and_training_tables')
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        self.evaluations = self.fixture.evaluations
        self.binding = self.fixture.binding
        self.binding['dataset'].update(samples=[{'image': 'images/val/fixture.png'}], split='val', purpose='evaluation', images=1, boxes=5)
        self.binding['categories'] = [{'class_id': i, 'name': n, 'source_category_id': COCO_CATEGORY_IDS[i],
                                       'evaluator_internal_category_id': i+1} for i,n in enumerate(CLASS_NAMES)]
        self.binding['category_mapping_sha256'] = digest(self.binding['categories'])
        self.binding['protocol'] = protocol()
        self.binding['protocol_sha256'] = digest(protocol())

    def success(self, key, mutate=None):
        item = self.fixture.create(key)
        row = self.evaluations.claim()
        result = complete_result(self.binding)
        if mutate: mutate(result)
        self.evaluations.succeed(row, result, [])
        return item['id']

    def pair(self):
        return self.success('a'), self.success('b')

    def assert_problem(self, status, code, operation):
        with self.assertRaises(Problem) as caught: operation()
        self.assertEqual((caught.exception.status, caught.exception.code), (status, code))

    def test_same_model_distinct_records_zero_and_read_only_sql(self):
        a, b = self.pair()
        original = self.fixture.runtime.connection
        statements = []
        @contextlib.contextmanager
        def read_only():
            with original() as db:
                db.execute('PRAGMA query_only=ON')
                db.set_trace_callback(statements.append)
                yield db
        before = self.fixture.store.model('demo', self.fixture.model_id)
        with mock.patch.object(self.fixture.runtime, 'connection', read_only):
            value = compare(self.evaluations, 'demo', a, b)
        self.assertTrue(value['compatible'])
        self.assertEqual(value['incompatibilities'], [])
        self.assertEqual(set(value['delta'].values()), {0})
        self.assertEqual(value['a']['model_version_id'], value['b']['model_version_id'])
        self.assertEqual(value['a']['result']['digests']['prediction_sha256'], value['b']['result']['digests']['prediction_sha256'])
        self.assertEqual(self.fixture.store.model('demo', self.fixture.model_id), before)
        self.assertTrue(statements)
        self.assertTrue(all(s.lstrip().upper().startswith('SELECT ') for s in statements), statements)

    def test_distinct_ids_and_strict_id_validation(self):
        a, b = self.pair()
        for bad in ('', 'mev_bad', a.upper(), None, 12):
            self.assert_problem(400, 'invalid_input', lambda: compare(self.evaluations, 'demo', a, bad))
        self.assert_problem(400, 'invalid_input', lambda: compare(self.evaluations, 'demo', a, a))
        self.assert_problem(404, 'not_found', lambda: compare(self.evaluations, 'other', a, b))

    def test_ownership_precedes_nonterminal_and_tamper_both_directions(self):
        a = self.fixture.create('queued')['id']
        missing = 'mev_' + 'f' * 32
        for x, y in ((a, missing), (missing, a)):
            self.assert_problem(404, 'not_found', lambda: compare(self.evaluations, 'demo', x, y))
        self.evaluations.claim(); self.evaluations.fail(a, 'fixture')
        b = self.success('succeeded')
        self.evaluations.evidence_path(b).write_text('[{}]')
        for x, y in ((b, missing), (missing, b)):
            self.assert_problem(404, 'not_found', lambda: compare(self.evaluations, 'demo', x, y))

    def test_all_nonterminal_states(self):
        a = self.success('success')
        b = self.fixture.create('pending')['id']
        for status in ('queued', 'running', 'failed'):
            if status == 'running': self.evaluations.claim()
            if status == 'failed': self.evaluations.fail(b, 'fixture')
            self.assert_problem(409, 'evaluation_not_succeeded', lambda: compare(self.evaluations, 'demo', a, b))
            self.assert_problem(409, 'evaluation_not_succeeded', lambda: compare(self.evaluations, 'demo', b, a))

    def test_prediction_result_and_binding_tamper(self):
        for target in ('prediction', 'result', 'binding'):
            with self.subTest(target=target):
                a = self.success(target+'a'); b = self.success(target+'b')
                if target == 'prediction': self.evaluations.evidence_path(b).write_text('[{}]')
                else:
                    with self.fixture.runtime.connection() as db:
                        if target == 'result':
                            db.execute('DROP TRIGGER model_evaluation_result_update_immutable')
                            db.execute('UPDATE model_evaluation_results SET result_json=? WHERE evaluation_id=?', ('{}', b))
                        else:
                            db.execute('DROP TRIGGER model_evaluation_identity_immutable')
                            db.execute('DROP TRIGGER model_evaluation_terminal_immutable')
                            db.execute('UPDATE model_evaluations SET binding_sha256=? WHERE id=?', ('bad', b))
                self.assert_problem(409, 'evaluation_integrity', lambda: compare(self.evaluations, 'demo', a, b))

    def test_signed_deltas_swap_null_and_counts(self):
        a = self.success('a')
        def change(result):
            result['metrics'].update(map_50=.6, map_50_95=.2)
            result['metrics']['per_class'][0].update(ap_50=.6, ap_50_95=.2)
            result['operating_point']['totals'].update(tp=3, fp=1, fn=2, precision=.75, recall=.6)
            result['operating_point']['per_class'][0].update(tp=3, fp=1, fn=2, precision=.75, recall=.6)
        b = self.success('b', change)
        forward = compare(self.evaluations, 'demo', a, b)['delta']
        reverse = compare(self.evaluations, 'demo', b, a)['delta']
        self.assertEqual((forward['tp'], forward['fp'], forward['fn']), (1, -1, -1))
        self.assertAlmostEqual(forward['map_50'], .2)
        self.assertAlmostEqual(forward['map_50_95'], -.05)
        self.assertEqual(forward['ar_100'], 0)
        for key, value in forward.items():
            self.assertEqual(reverse[key], None if value is None else -value)

    def test_valid_no_ground_truth_and_no_predictions_preserve_null(self):
        self.binding['dataset']['boxes'] = 0
        def empty(result):
            m = result['metrics']
            m.update(status='no_ground_truth', map_50=None, map_50_95=None, ar_100=None)
            m['counts'].update(images_with_ground_truth=0, images_without_ground_truth=1,
                               images_with_predictions=0, ground_truth_boxes=0, predictions=0, categories_with_ground_truth=0)
            for row in m['per_class']:
                row.update(ground_truth_boxes=0, predictions=0, status='no_ground_truth', ap_50=None, ap_50_95=None, ar_100=None)
            for row in result['operating_point']['per_class'] + [result['operating_point']['totals']]:
                row.update(tp=0, fp=0, fn=0, precision=None, recall=None)
        a, b = self.success('empty-a', empty), self.success('empty-b', empty)
        value = compare(self.evaluations, 'demo', a, b)
        self.assertTrue(value['compatible'])
        for key in ('map_50','map_50_95','ar_100','precision','recall'): self.assertIsNone(value['delta'][key])
        for key in ('tp','fp','fn'): self.assertEqual(value['delta'][key], 0)

    def test_valid_ground_truth_without_predictions_has_measured_zero_not_null_ap(self):
        def no_predictions(result):
            m = result['metrics']; m.update(map_50=0, map_50_95=0, ar_100=0)
            m['counts'].update(images_with_predictions=0, predictions=0)
            m['per_class'][0].update(predictions=0, ap_50=0, ap_50_95=0, ar_100=0)
            for row in (result['operating_point']['per_class'][0], result['operating_point']['totals']):
                row.update(tp=0, fp=0, fn=5, precision=None, recall=0)
        a, b = self.success('no-pred-a', no_predictions), self.success('no-pred-b', no_predictions)
        value = compare(self.evaluations, 'demo', a, b)
        self.assertEqual(value['delta']['map_50'], 0)
        self.assertEqual(value['delta']['recall'], 0)
        self.assertIsNone(value['delta']['precision'])

